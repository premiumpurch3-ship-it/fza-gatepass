"""Generates docs/openapi.json and the endpoint table of docs/API.md from the live FastAPI schema:  python scripts/gen_api_doc.py"""
import json, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
os.environ.setdefault("DATABASE_URL", "postgresql+psycopg://x:x@localhost/x")
from app.main import app
spec = app.openapi(); docs = os.path.join(os.path.dirname(__file__), "..", "..", "docs")
json.dump(spec, open(os.path.join(docs, "openapi.json"), "w"), indent=1)
groups: dict = {}
for path, ops in spec["paths"].items():
    for m, op in ops.items():
        groups.setdefault((op.get("tags") or ["other"])[0], []).append((path, m.upper(), op.get("summary", "")))
out = ["<!-- generated by backend/scripts/gen_api_doc.py -->", ""]
for g in sorted(groups):
    out += [f"### {g}", "", "| Method | Path | Handler |", "|---|---|---|"]
    out += [f"| {m} | `{p}` | {s} |" for p, m, s in sorted(groups[g])]
    out.append("")
open(os.path.join(docs, "_api_table.md"), "w").write("\n".join(out))
print(sum(len(v) for v in groups.values()), "operations in", len(groups), "groups")
